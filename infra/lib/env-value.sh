# shellcheck shell=bash
# CampTribe — прочитати значення з .env ДОСЛІВНО, не виконуючи файл (CAMP-349).
#
# 🔴 НАВІЩО. До 19.10.2026 два місця читали `.env` так:
#
#     set -a; . "$ENVF"; set +a
#
# Тобто виконували файл оболонкою. Коли у `.env` зʼявився рядок
# `SMTP_PASSWORD=…)…`, читання почало падати з
# `syntax error near unexpected token ')'` — і щонічний бекап не робився
# ТРИ НОЧІ поспіль (17, 18, 19.10), поки сайт спокійно працював.
#
# Працював він тому, що systemd читає той самий файл через
# `EnvironmentFile=`, а воно НЕ оболонка: просто `KEY=VALUE`. Тобто
# формат файла ніколи й не був шел-скриптом — ним його зробили ми.
#
# 🔴 І ЦЕ НЕ ЛИШЕ ПРО ПАДІННЯ. Виконувати файл із секретами означає, що
# будь-яке `$(…)` чи зворотні лапки в значенні ВИКОНАЮТЬСЯ. Пароль, у
# якому випадково є `$(rm -rf …)`, перестає бути паролем і стає
# командою. Тут значення береться як текст і текстом лишається.
#
# Поведінка свідомо повторює systemd `EnvironmentFile`:
#   · порожні рядки й ті, що починаються з `#`, пропускаються;
#   · `export KEY=…` теж приймається — так пишуть руками;
#   · лапки знімаються, лише якщо охоплюють УСЕ значення;
#   · при повторі ключа виграє ОСТАННІЙ, як і в оболонці;
#   · `\r` у кінці (файл із Windows) зрізається.

env_value() {
  local file="$1" key="$2" line v
  [ -f "$file" ] || return 1
  line="$(grep -E "^[[:space:]]*(export[[:space:]]+)?${key}=" "$file" 2>/dev/null | tail -n 1)" || true
  [ -n "$line" ] || return 1
  v="${line#*=}"
  v="${v%$'\r'}"
  case "$v" in
    \'*\') [ "${#v}" -ge 2 ] && { v="${v#\'}"; v="${v%\'}"; } ;;
    \"*\") [ "${#v}" -ge 2 ] && { v="${v#\"}"; v="${v%\"}"; } ;;
  esac
  printf '%s' "$v"
}
