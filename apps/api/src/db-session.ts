import { config as loadDotenv } from 'dotenv';

// 🔴 ДО обчислення PG_CONNECTION нижче — див. коментар над ним.
loadDotenv({ quiet: true });

/**
 * CAMP-338 — пояс сесії до бази задається НАМИ, а не машиною.
 *
 * 🔴 ЩО ЗАМІРЯНО 03.11.2026.
 *
 * У схемі `public` чотирнадцять колонок `timestamp without time zone`,
 * із них чотири несуть дані людей: `users.created_at`,
 * `trips.created_at`, `reviews.created_at`,
 * `photo_submissions.created_at`.
 *
 * Наївна колонка зберігає місцевий час ТІЄЇ МАШИНИ, що писала рядок, а
 * приведення `created_at::timestamptz` читає його через пояс СЕСІЇ. Тобто
 * та сама мить дає різні значення залежно від того, хто виконує запит:
 *
 *   ноутбук у Europe/Brussels   →  правильна мить
 *   прод у UTC                  →  інша мить, різниця дві години
 *
 * Прод сьогодні в UTC (`SHOW TimeZone` → `Etc/UTC`, `timedatectl` → UTC),
 * тож рядки на ньому узгоджені. Але тримається це НЕ на рішенні, а на
 * тому, що машина така сталася. Один скрипт, запущений із ноута проти
 * прод-бази, пише місцевий час — і відрізнити його постфактум буде вже
 * неможливо.
 *
 * 🔴 ЦЕ НЕ ЗАМІНЮЄ МІГРАЦІЇ НА `timestamptz`. Вона потрібна й лишається
 * окремою карткою: тут прибрано мовчазне псування нових записів, а не
 * двозначність самого типу. Міграція безпечна саме тому, що всі наявні
 * рядки на проді писались у UTC, — але вона чіпає 63 тисячі рядків
 * `camping_spots` і потребує вікна.
 */

/**
 * Параметри зʼєднання, які драйвер `pg` передає серверу.
 *
 * `-c timezone=UTC` задає пояс СЕСІЇ, тобто діє на кожен запит цього
 * зʼєднання незалежно від `TZ` процесу й від налаштувань сервера.
 */
export const PG_SESSION_OPTIONS = '-c timezone=UTC';

/** `extra` для TypeORM: одне означення на всі точки підключення. */
export const PG_EXTRA = Object.freeze({ options: PG_SESSION_OPTIONS });

/**
 * Усе, чим обидва пули зʼєднуються з базою — ОДНИМ переліком.
 *
 * 🔴 ЦЕ ЗАКРИВАЄ ДІРКУ, ЯКУ КАРТКА CAMP-433 НАЗВАЛА, А ТЕСТ НЕ ЛОВИВ.
 *
 * «Спосіб перевірки» вимагав дослівно: прибрати `extra: PG_EXTRA` з
 * `data-source.ts` — спек має почервоніти; прибрати з `app.module.ts` —
 * теж; два місця, дві мутації, два червоних.
 *
 * Заміряно 03.11.2026: ОБИДВІ мутації вижили. `db-session.db.spec.ts`
 * лишався зеленим (3 passed) в обох випадках, бо він відкриває ВЛАСНИЙ
 * `Client` із `options: PG_SESSION_OPTIONS` і до справжніх пулів не
 * торкається. Тобто доводив, що константа працює, а не що її вживають.
 *
 * Два місця з однаковим рядком не звіряються — вони розходяться. Тепер
 * місце одне, і `pools.db.spec.ts` читає цей обʼєкт із СПРАВЖНЬОГО
 * `AppDataSource.options`, а не з тексту файла.
 */
export const PG_CONNECTION = Object.freeze({
  type: 'postgres' as const,
  url: process.env.DATABASE_URL ?? 'postgres://localhost:5432/camptribe_dev',
  extra: PG_EXTRA,
});

/**
 * 🔴 ЧОМУ `.env` ЧИТАЄТЬСЯ ТУТ, А НЕ ЛИШЕ В `ConfigModule.forRoot()`.
 *
 * Заміряно 04.11.2026: нічний деплой упав на тимчасовій API —
 * `Unable to connect to the database. Retrying (1)…(10)` і вихід із
 * кодом 1. Деплой запускає її як `env PORT=3002 node dist/main` із
 * `.env` у теці, а не в оточенні (systemd-юніт живої API має
 * `EnvironmentFile`, тимчасова — ні). До CAMP-433 вираз
 * `process.env.DATABASE_URL ?? …` стояв усередині літерала
 * `TypeOrmModule.forRoot({...})`, який обчислюється ПІСЛЯ
 * `ConfigModule.forRoot()` у тому ж масиві імпортів — і `.env` уже був
 * прочитаний. CAMP-433 перенесла його сюди, у модульну область, а
 * `app.module.ts` і `data-source.ts` імпортують цей файл ПЕРШИМ рядком:
 * `PG_CONNECTION` обчислювався до того, як хтось узагалі відкрив `.env`,
 * і обидва пули йшли в `camptribe_dev`, якої на машині немає.
 *
 * Локально це не видно: `camptribe_dev` на ноуті існує, API стартує,
 * лише бекенд у `pg_stat_activity` сидить не в тій базі. У CI — теж:
 * кожен запуск API там має `DATABASE_URL` в оточенні процесу.
 *
 * Тому `.env` завантажується ТУТ, перед обчисленням, і порядок імпортів
 * більше нічого не вирішує. `quiet`, бо dotenv ≥17 інакше друкує банер
 * у stderr на кожному старті. `ConfigModule.forRoot()` потім читає той
 * самий файл і нічого не перезаписує.
 *
 * Сторож: `startup-env.db.spec.ts` — запускає `dist/main` як деплой і
 * читає з `pg_stat_activity`, у якій базі опинився його бекенд.
 */
