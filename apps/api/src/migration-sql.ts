/**
 * Вирізати з файлу міграції один її оператор за назвою об'єкта.
 *
 * 🔴 ЧОМУ ЦЕ ТУТ, А НЕ В СПЕЦИФІКАЦІЇ. Функція жила в
 * `rental/review-permission.db.spec.ts` і звідти її імпортував новий
 * `spots/spot-claim.db.spec.ts` — тобто імпорт тягнув за собою ВЕСЬ той
 * файл: його `beforeAll`, його `describe`, його таблиці. Новий тест
 * падав із `function uuid_generate_v4() does not exist`, і падала при
 * цьому ЧУЖА перевірка, яку він ніколи не збирався запускати.
 *
 * Специфікація — не бібліотека. Спільне живе окремо.
 *
 * 🔴 А сама ідея лишається тією самою: тест читає SQL із файлу міграції,
 * бо копія обмеження в тесті перевіряла б копію — прибери `CHECK` із
 * міграції, і тест лишиться зеленим, стережучи текст, якого в базі вже
 * немає.
 *
 * Оператори лежать усередині `queryRunner.query(\`…\`)`, тому береться
 * вміст зворотних лапок, що містять потрібне ім'я. Нуль або два збіги —
 * помилка: тест мусить знати, що саме він виконує.
 */
export function statementFor(text: string, needle: string): string {
  const blocks = [...text.matchAll(/`([^`]*)`/g)].map((m) => m[1]);
  const found = blocks.filter((b) => b.includes(needle));
  if (found.length !== 1) {
    throw new Error(
      `у міграції знайдено ${found.length} операторів із «${needle}», а треба рівно один`,
    );
  }
  return found[0];
}
