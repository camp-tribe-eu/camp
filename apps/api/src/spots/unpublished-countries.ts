// CAMP-490: країни, які ми ТРИМАЄМО в базі, але читачеві НЕ показуємо.
//
// 🔴 ЦЕ НЕ ПЕРЕЛІК ОБЛАСТІ ПРОЄКТУ. Область — це `osm/eu-member-states.json`
// і `EU_MEMBER_STATES` у вебі: 27 держав, яких торкаються `drop-non-eu.mjs`
// (видаляє з бази рядки поза ЄС), `load-country-boundaries.sh` і
// `check-eu-scope.mjs`. Кіпр — член Союзу. Прибрати його звідти означало б
// стерти 60 рядків із бази, а рішення власника було «не показувати», а не
// «стерти». Тому «не публікуємо» живе окремо від «в області».
//
// Що тут стоїть і чому — одне місце, де це можна прочитати:
//
//   cy — Кіпр. Рішення власника 11.11.2026: «прибери». Уперше ухвалено
//        26.10.2026 («Кіпр не показуємо»). Рядки лишаються в базі (60 на
//        11.11.2026, 36 із них без регіону), їх бачать імпорт і звірка;
//        читач їх не бачить: 404 на сторінках, нічого в мапі, пошуку,
//        індексі статичної генерації й підсумках.
//
// 🔴 Редиректів немає навмисно. Заміряно 11.11.2026: пошук `site:camptribe.eu`
// не повертає нічого, а сайт був відкритий 11 год 41 хв і краулер жодної
// сторінки кемпінгу не брав. Мапа редиректів стоїть на ~81% крайового
// бюджету (CAMP-472), тож 404 тут дешевше й чесніше.
//
// Додати країну — один рядок у масиві й рядок причини вище. `ax` (Åland)
// сюди НЕ внесено: рішення власника по ньому ще не ухвалено.
//
// 🔴 Сторож, що міряє ВИВІД, а не цей файл:
// `scripts/ci/check-unpublished-countries.mjs` питає кожну точку входу й
// червоніє, якщо код із переліку з'явився у відповіді. Перелік він читає
// з цього файлу.

export const UNPUBLISHED_COUNTRIES = ['cy'] as const;

for (const code of UNPUBLISHED_COUNTRIES) {
  // Код іде в SQL літералом, тож він мусить бути рівно двома малими
  // літерами: усе інше — помилка завантаження, а не запит із дірою.
  if (!/^[a-z]{2}$/.test(code)) {
    throw new Error(`UNPUBLISHED_COUNTRIES: "${code}" is not a 2-letter code`);
  }
}

/** Чи прихований цей код (будь-який регістр). */
export function isUnpublishedCountry(
  country: string | null | undefined,
): boolean {
  return (
    typeof country === 'string' &&
    (UNPUBLISHED_COUNTRIES as readonly string[]).includes(country.toLowerCase())
  );
}

/**
 * Фрагмент `WHERE`: рядок країни, яку публікуємо. `alias` — псевдонім
 * `camping_spots` у запиті (або сама назва таблиці, якщо псевдоніма немає).
 *
 * `country` у базі NOT NULL, тож `NOT IN` не загубить рядок через NULL.
 */
export function publishedCountrySql(alias: string): string {
  const list = UNPUBLISHED_COUNTRIES.map((c) => `'${c}'`).join(', ');
  return `lower(${alias}.country) NOT IN (${list})`;
}
