// «Bari» віддає сміття з `osm_route_poi` чи з паркінгів. Індекс пошуку не
// торкається жодної з цих таблиць — він читає лише `camping_spots`, і
// кожен «сміттєвий» результат там справжній рядок OpenStreetMap з
// `tourism=caravan_site`. Сміття не з іншої таблиці, а з назви: мапер
// позначив майданчиком паркінг, мийку, окреме місце під фургон — і назва
// в нього така, яка вона на табличці.
//
// Заміряно 15.11.2026 на `camptribe_dev` (63 159 рядків, 52 527 у
// індексі пошуку):
//
//   • голий код замість назви — «P1», «E01», «Z211», «B», «Nr 49»:
//     215 рядків у таблиці, 180 із них у Баден-Вюртемберзі (номери
//     окремих місць під фургон великого майданчика; 154 із них уже з
//     `missing_since`, тож в індекс і так не йдуть). Такий рядок не можна
//     ні знайти за назвою, ні підписати карткою;
//   • мийка автомобілів: 3 рядки на всю базу.
//
// Ефект правила на індекс: 52 527 → 52 499 документів, тобто 28 рядків
// (26 голих кодів без сліду + 2 мийки). Запит: див. `search-noise.db.spec.ts`
// і опис PR — там же до/після на п'яти пошукових запитах.
//
// 🔴 ЦЕ ЕВРИСТИКА, І ВОНА МАЛА ХИБНІ СПРАЦЮВАННЯ, ЯКІ ЗАМІР ЗНАЙШОВ. Перша
// редакція правила була лише про форму назви — і вона викинула б «OP29»
// й «LF13» (справжні кемпінги, що названі за своїм сайтом: op29.nl,
// lf13.nl) та «Oz» (Oz Vama Veche, із сайтом і поштою). Тому голий код —
// сміття лише тоді, коли за ним немає ЖОДНОГО сліду кемпінгу: ні
// сайту, ні пошти, ні опису, ні зірок. З 215 така вимога лишає 3
// справжні й відсікає 212.
//
// 🔴 «Daniele Autolavagaggio a mano e sosta camper» ЛИШАЄТЬСЯ. Це той
// рядок, який власник у ревʼю назвав автомийкою, і він справді мийка —
// але в назві прямо написано «sosta camper», а в записі є вода, туалет і
// електрика. Правило «мийка» спрацьовує лише коли в назві НЕМАЄ жодного
// слова про ночівлю (camp, caravan, sosta, stellplatz, aire, area, rv…).
// Викидати запис, який сам себе називає стоянкою для кемперів, — це вже
// не чистка, а втрата. Під правило потрапляють «Autolavaggio Cavalcante»
// (годинник 24/7, жодного слова про ночівлю) і «Hobby Park Wash».
//
// 🔴 ЦЕ ТІЛЬКИ ПОШУК. Сторінка кемпінгу, мапа й перелік регіону цього
// запису не чіпають: його можна знайти там, де він є, а не друкувати
// першим у відповіді на «Bari». Площа сторожа (≈215 рядків із 52 527)
// не більша за площу дефекту, який він прибирає.
//
// 🔴 ASCII-КЛАСИ, А НЕ `[[:alpha:]]`. `[[:alpha:]]` залежить від локалі
// бази: на `C`-локалі грецькі й болгарські назви не мають жодної
// «літери» і всі стали б «голим кодом». `[A-Za-z]` від локалі не залежить.

/** Колонки рядка, які правилу треба бачити. Імена — вирази SQL. */
export interface NoiseColumns {
  /** Назва, уже злита з повʼязаним рядком (`mergedNameSql`). */
  name: string;
  website: string;
  description: string;
  stars: string;
  contact: string;
}

/** Слова, що називають мийку, а не місце ночівлі. */
export const CAR_WASH_WORDS = String.raw`(autolav|lavaggio|car ?wash|autowasch|waschstra|lavage|lavadero|myjnia|autopesu|\mwash\M)`;

/** Слова, що кажуть: тут стають на ніч. Є хоч одне — це не мийка. */
export const STAY_WORDS = String.raw`(camp|caravan|wohnmobil|womo|stellplatz|sosta|\maire\M|\marea\M|\mrv\M|motorhome|kemp)`;

/**
 * Предикат: `true`, коли рядок МОЖНА класти в індекс пошуку.
 *
 * Безіменний рядок проходить: 212 безіменних хорватських кемпінгів
 * знаходяться за регіоном і оточенням, це рішення CAMP-67.
 */
export function searchableSql(c: NoiseColumns): string {
  const bareCode =
    `(char_length(${c.name}) <= 2` +
    ` OR ${c.name} ~ '^[A-Za-z]{1,2}[ .-]?[0-9]{1,4}[A-Za-z]?$'` +
    ` OR ${c.name} ~ '^[0-9]+$')`;
  const noTrace =
    `(${c.website} IS NULL` +
    ` AND ${c.description} IS NULL` +
    ` AND ${c.stars} IS NULL` +
    ` AND ${c.contact}->>'website' IS NULL` +
    ` AND ${c.contact}->>'email' IS NULL)`;
  const carWash = `(${c.name} ~* '${CAR_WASH_WORDS}' AND ${c.name} !~* '${STAY_WORDS}')`;

  return `(${c.name} IS NULL OR NOT ((${bareCode} AND ${noTrace}) OR ${carWash}))`;
}
