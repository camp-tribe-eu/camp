// 🔴 ЧОМУ ЦЕ ОКРЕМИЙ ФАЙЛ, А НЕ РЯДОК У ТЕСТІ. Тест у браузері не може
// перевірити власний таймаут: він або встиг, або ні, і обидва результати
// нічого не кажуть про ФОРМУЛУ. Винесене сюди число перевіряється
// модульним тестом, тобто може почервоніти.
//
// 🔴 І ЧОМУ ВЗАГАЛІ ФОРМУЛА. Цей тест падав ДВІЧІ з тієї самої причини:
// бюджет був константою (30 000 мс, потім 90 000 через `test.slow()`), а
// вартість росла разом із каталогом гайдів. 13.10.2026 — перший раз,
// 16.10.2026 — ще тричі вже на потроєному. Множити константу вчетверте
// означало б лікувати не ту причину.
//
// Обхід N сторінок коштує Θ(N) — це неможливо обійти, скільки б запитів
// не йшло паралельно. Тому лікуємо не зростання, а те, що МЕЖА його не
// враховувала.

/** Старт тесту, два браузерні завантаження для звірки методу, запас. */
export const BUDGET_FIXED_MS = 20_000;

/**
 * Скільки даємо на один фасет.
 *
 * Заміряно 21.10.2026 проти ЗІБРАНОГО сайту (`next start`), 31 фасет,
 * медіана з трьох: див. опис PR. Тут стоїть величина з запасом у
 * кілька разів — бюджет мусить терпіти повільний спільний раннер, а не
 * описувати найкращий випадок.
 */
export const BUDGET_PER_FACET_MS = 900;

/**
 * Бюджет на обхід `n` фасетів.
 *
 * 🔴 МУСИТЬ СТРОГО ЗРОСТАТИ. Якщо колись хтось зробить це константою,
 * модульний тест почервоніє — а каталог рано чи пізно знову переросте
 * межу, і падіння виглядатиме як флуктуація, а не як межа.
 */
export function facetBudgetMs(n: number): number {
  if (!Number.isInteger(n) || n < 0) {
    throw new Error(`facetBudgetMs: фасетів мусить бути ціле ≥ 0, дано ${n}`);
  }
  return BUDGET_FIXED_MS + BUDGET_PER_FACET_MS * n;
}
