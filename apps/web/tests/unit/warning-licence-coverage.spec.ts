import { readFileSync } from 'node:fs';
import path from 'node:path';
import { expect, test } from '@playwright/test';
import { CLAUSES, DISCLAIMER_VERBATIM, PANEL_CHROME } from './warning-licence';

// CAMP-152 — чи кожна умова ліцензії взагалі має тест.
//
// 🔴 ЦЕ ІНШЕ ПИТАННЯ, НІЖ «ЧИ ТЕСТИ ПРАЦЮЮТЬ». Матриця, заміряна
// 13.10.2026, довела, що працюють: прибери кредит із компонента — і
// червоніють тести 5.2 і 5.3; прибери час — 5.4; підміни час випуску
// на `onset` — теж 5.4; прибери посилання — 5.5; прибери дисклеймер —
// 5.7. Шість із семи умов ізолюються власним тестом, сьома (5.1)
// тримається списком дозволених слів.
//
// Але матриця каже лише про тести, які Є. Видали тест на 5.5 — і все
// лишиться зеленим, бо ніщо не питає, чи він існує. Порушення
// ліцензії невидиме, доки не стане дорогим, і найдешевший спосіб його
// влаштувати — прибрати тест, а не елемент.
//
// 🔴 ЧОГО ЦЯ ПЕРЕВІРКА НЕ ДОВОДИТЬ, сказано прямо: вона дивиться на
// НАЗВИ тестів. Тест, названий «clause 5.5» і порожній усередині,
// задовольнить її. Доказ якості — матриця вище, і вона в тому ж
// репозиторії; це перевірка на присутність, і вона коштує стільки,
// скільки коштує.

const SPEC = path.join(process.cwd(), 'tests', 'unit', 'warning-panel.spec.ts');
const spec = readFileSync(SPEC, 'utf8');

/**
 * Чи є в назві якогось тесту цей рядок.
 *
 * 🔴 ОДНА ФУНКЦІЯ НА ОБИДВА ВЖИТКИ, І ПЕРША ВЕРСІЯ МАЛА ЇХ ДВІ.
 * Контрольний випадок («умови 5.9 немає») тримав власну копію пошуку,
 * тож перевіряв не той код: мутація `.some(() => true)` у циклі вище
 * лишила всі 11 тестів зеленими. Контроль, який виконує іншу копію,
 * нічого не контролює.
 */
const titledSomewhere = (needle: string): boolean =>
  spec
    .split('\n')
    .filter((l) => /\btest\(/.test(l))
    .some((l) => l.includes(needle));

test('умов рівно сім — стільки, скільки їх у клаузулі 5', () => {
  // 🔴 Не `CLAUSES.length > 0`: сім — це число з ліцензії. Восьма
  // умова, додана без тесту, мусить впасти тут, а не пройти тому, що
  // «список непорожній».
  expect(CLAUSES.length).toBe(7);
});

test('жодна умова не названа двічі', () => {
  expect([...new Set(CLAUSES.map((c) => c.id))].length).toBe(CLAUSES.length);
});

// 🔴 НОМЕР У НАЗВІ ТЕСТУ, А НЕ `clause.id`. Дві умови з одним `id`
// дали б двом згенерованим тестам однакову назву, Playwright упав би з
// помилкою конфігурації — і прогін без жодного числа легко прочитати
// як «мутацію спіймано». Індекс робить назви унікальними, і перевірка
// на дублікати вище доживає до того, щоб спрацювати.
CLAUSES.forEach((clause, i) => {
  test(`умова №${i + 1} має свій тест у warning-panel.spec.ts`, () => {
    expect(
      titledSomewhere(clause.id),
      `${clause.id} — «${clause.text.slice(0, 60)}…» — не має тесту`,
    ).toBe(true);
  });
});

test('🔴 той самий пошук не знаходить умови, якої немає', () => {
  // Без цього випадку пошук міг би повертати `true` завжди — і повертав:
  // мутація `.some(() => true)` пережила першу версію цього файлу, бо
  // контроль мав власну копію коду.
  expect(titledSomewhere('clause 5.9')).toBe(false);
});

test('дисклеймер у списку умов — той самий рядок, що й у дозволених словах', () => {
  // 🔴 Дві копії тексту ліцензії розійшлися б мовчки, і версія, яку
  // читає тест, виглядала б так само, як версія, яку бачить читач.
  const c57 = CLAUSES.find((c) => c.id === 'clause 5.7');
  expect(c57?.text.includes(DISCLAIMER_VERBATIM)).toBe(true);
  expect(PANEL_CHROME.includes(DISCLAIMER_VERBATIM)).toBe(true);
});
