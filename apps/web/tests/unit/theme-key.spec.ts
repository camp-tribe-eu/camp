import { expect, test } from '@playwright/test';

import { THEME_KEY } from '@/components/theme-toggle';
import { THEME_BOOTSTRAP } from '@/lib/theme-bootstrap';

/**
 * CAMP-448 — ключ теми записаний у двох місцях, і це мусить лишитись
 * однією правдою.
 *
 * 🔴 ЧОМУ КОПІЙ ДВІ. Скрипт у `<head>` ставиться із серверного макета й
 * не може імпортувати з клієнтського компонента. А сторож правових
 * сторінок (`legal-claims.ts`) розкриває ключ `.setItem(` лише тоді,
 * коли сталу оголошено в тому самому файлі, — імпорт він чесно
 * відмовляється називати.
 *
 * 🔴 ЩО СТАЛОСЬ БИ БЕЗ ЦЬОГО ТЕСТУ: перейменування в одному місці дало б
 * сайт, який ПИШЕ один ключ, а ЧИТАЄ до першого малювання інший. Вибір
 * теми просто перестав би переживати перезавантаження — мовчки, бо
 * обидві половини працюють.
 */

test('🔴 скрипт у <head> читає рівно той ключ, що пише компонент', () => {
  expect(THEME_KEY).toBe('camptribe.theme');
  expect(
    THEME_BOOTSTRAP,
    `скрипт не згадує ключ «${THEME_KEY}»`,
  ).toContain(`'${THEME_KEY}'`);
});

test('🔴 скрипт ставить атрибут лише для відомих значень', () => {
  // Читається сам рядок, бо саме він доїде в `<head>`: перевіряти
  // «десь є перевірка» безглуздо, тут важлива та, що поїде.
  expect(THEME_BOOTSTRAP).toContain("t==='dark'");
  expect(THEME_BOOTSTRAP).toContain("t==='light'");
  expect(THEME_BOOTSTRAP).toContain('catch');
});
