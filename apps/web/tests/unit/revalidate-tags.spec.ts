import { expect, test } from "@playwright/test";
import { ALLOWED_TAGS } from "@/lib/revalidate-tags";
import { PAGE_TAG } from "@/lib/page-content";
import { NAV_TAG } from "@/lib/navigation";

// 🔴 CAMP-364 — мітку `pages` не міг скинути НІХТО.
//
// Заміряно рецензією #308: `POST /internal/revalidate?tag=pages` віддавав
// `400 {"allowed":["navigation"]}`, і жоден виклик у репозиторії цю
// мітку не згадував. Тобто ввесь текст CMS — сторінки, правові
// документи, дописи блогу — оновлювався виключно витримкою 86 400 с,
// тоді як коментар у `lib/posts.ts` стверджував «одна мітка — один
// вебхук, який не можна налаштувати наполовину». Мітка існувала, і
// скинути її було нічим.
//
// 🔴 І ЧОМУ ЦЕ ЮНІТ, А НЕ E2E. Першою редакцією я написав e2e, який
// питав обробник по HTTP, — він упав у ВСІХ ЧОТИРЬОХ браузерах. Бо
// секрет перевіряється ПЕРШИМ: без `REVALIDATE_SECRET` (а в CI його
// немає) відповідь 503, і про мітки в ній не йдеться. Перелік міток по
// HTTP у CI не видно ніколи — тест стояв на хибній засновку.
test.describe("🔴 мітки, які дозволено скидати", () => {
  // 🔴 ПЕРЕЛІК ПОРОЖНІЙ НАВМИСНО — CAMP-396, заміряно на проді 26.10.2026.
  //
  // Один `revalidateTag('navigation')` перевів 55 269 сторінок кемпінгів і
  // 1 256 гайдів у 404 ДО ПЕРЕЗАПУСКУ СЛУЖБИ. Мітка `pages` так само клала
  // `/legal/*`. Гине рівно те, що мітку споживало, а меню живе в кореневому
  // макеті — тож його мітку їсть кожна сторінка.
  //
  // 🔴 Очевидний ремонт — `dynamicParams = true` — ХИБНИЙ, я його зробив і
  // відкотив: він ламає CAMP-73. Заміряно на `/blog/<неіснуючий>`, який уже
  // має `true`: увесь файл 34 399 байт, рядки 404 в ньому є; БЕЗ `<script>`
  // лишається 1 302 байти і не лишається нічого. Вміст 404 їде в
  // RSC-навантаженні, тож без JS сторінка порожня — і для робота теж.
  test("перелік ПОРОЖНІЙ: жодна мітка не може покласти каталог", () => {
    expect([...ALLOWED_TAGS.keys()]).toEqual([]);
  });

  // Мітки в коді лишились — вони описують, що чим кешується. Зникла лише
  // можливість скинути їх ЗЗОВНІ.
  test("самі мітки нікуди не поділись", () => {
    expect(NAV_TAG).toBe("navigation");
    expect(PAGE_TAG).toBe("pages");
  });

  test("вигадана мітка не приймається — як і будь-яка інша", () => {
    expect(ALLOWED_TAGS.get("everything")).toBeUndefined();
    expect(ALLOWED_TAGS.get("navigation")).toBeUndefined();
  });
});
