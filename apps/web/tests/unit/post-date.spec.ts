import { expect, test } from "@playwright/test";
import { postDate } from "@/lib/posts";

// 🔴 CAMP-364 — дата допису не сміє залежати від поясу машини.
//
// Рецензія #308 заміряла: `2026-10-01T23:30:00.000Z` давало
// «1 October 2026» при TZ=UTC і «2 October 2026» при
// TZ=Europe/Brussels — а це пояс машини власника. При цьому
// `<time dateTime>`, `datePublished` у JSON-LD і `lastmod` у карті
// сайту кажуть UTC. Тобто читач і машини бачили б різні дати, залежно
// від того, на чиєму ноуті зібрали сайт.
test.describe("🔴 дата допису однакова в будь-якому поясі", () => {
  // Пізній вечір UTC — єдине вікно, де пояс узагалі щось змінює.
  const LATE = "2026-10-01T23:30:00.000Z";

  test("пізній вечір UTC лишається тим самим днем", () => {
    expect(postDate(LATE)).toBe("1 October 2026");
  });

  test("і рано-вранці UTC теж", () => {
    expect(postDate("2026-10-02T00:30:00.000Z")).toBe("2 October 2026");
  });

  // 🔴 Пара: без неї «дорівнює рядку» було б істинним і для функції,
  // що завжди віддає один день.
  test("різні дати дають різні рядки", () => {
    expect(postDate("2026-01-05T12:00:00.000Z")).toBe("5 January 2026");
    expect(postDate("2026-12-31T12:00:00.000Z")).toBe("31 December 2026");
  });
});
