import type { ReactNode } from 'react';

/**
 * CAMP-460 — розкладка розділу гідів із слотом для шухляди.
 *
 * 🔴 ЦЕЙ ФАЙЛ І Є ТИМ, ЩО ВМИКАЄ ПЕРЕХОПЛЕННЯ. Перехоплений маршрут
 * `@modal/(.)[slug]` без слота в розкладці не рендериться взагалі —
 * мовчки, без помилки. Тобто клік просто вів би на сторінку, і зміна
 * виглядала б «зробленою», доки хтось не відкриє її оком.
 *
 * Слот `modal` малюється ПІСЛЯ `children`, бо шухляда лежить поверх
 * сторінки, з якої її відкрили.
 */
export default function GuidesLayout({
  children,
  modal,
}: {
  children: ReactNode;
  modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
