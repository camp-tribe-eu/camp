// CAMP-229 — куди повернути людину після входу, і чому це НЕ `?next=`.
//
// 🔴 ЦЕ НАЙРИЗИКОВІШЕ МІСЦЕ КАРТКИ. До неї повернення не існувало, тож
// разом із ним зʼявляється ризик, якого досі не було: відкрите
// перенаправлення. Фішинговий лист із посиланням `/login?next=https://evil`
// відправляє людину на чужий сайт ВЖЕ ПІСЛЯ успішного входу, коли вона
// нам довіряє найбільше. Макет (Design/07-account.html, «Ніякого ?next=»)
// забороняє параметр у посиланні саме з цієї причини.
//
// 🔴 ДВА РІШЕННЯ, І ДРУГЕ ВАЖЛИВІШЕ ЗА ПЕРШЕ.
//
// ПЕРШЕ — ДЕ ЛЕЖИТЬ АДРЕСА: `sessionStorage` ЦІЄЇ ВКЛАДКИ, а не параметр.
//
//   · Параметр запиту пише ХТО ЗАВГОДНО: кожен лист, кожна сторінка, кожен
//     скрейпер. Сховище вкладки пише лише код цього origin, і він пише
//     його рівно в одному місці — коли сторінка за логіном відправляє
//     людину на /login (`rememberReturn` у кабінеті), з адреси ТОЇ САМОЇ
//     сторінки. Зловмисник у листі не має чим цього зробити: у посилання
//     немає шляху до сховища відкритої вкладки.
//   · Параметр видно в журналах сервера, в `Referer` кожного запиту, який
//     /login зробить далі, і в історії. Сховища там немає.
//   · Ціна, названа прямо: `sessionStorage` не переживає перехід у ІНШУ
//     вкладку. Лист із підтвердженням, відкритий в новій вкладці, починає з
//     порожнього сховища — і людина потрапляє на типове місце, а не туди,
//     де була. Це поступка, а не дефект: «за будь-якого сумніву — на
//     безпечне типове місце». Повернення з іншої вкладки (BroadcastChannel,
//     опитування сесії) — окрема картка CAMP-227 з її власним механізмом.
//   · `/login?next=…` ніким не читається ВЗАГАЛІ. Не «читається й
//     відкидається», а не читається: `takeReturn` не отримує адреси сторінки
//     взагалі (його підпис — сховище й годинник), а `LoginForm` не звертається
//     до `location` чи параметрів запиту. Друге тримає лише СТОРОЖ на текст
//     (`return-path.spec.ts`, коментарі відкинуто) — це сигналізація, а не
//     доказ; доказ — прогін у браузері з живим API, записаний в описі PR.
//
// ДРУГЕ — ЩО САМЕ ПРИЙМАЄТЬСЯ. Список заборонених форм (`//`, `\`, `javascript:`,
// `%2f`, `@`…) обходять новою формою, і кожна нова форма ламає список лише
// після того, як ним скористались. Тому тут питання протилежне: ЧОГО
// ЗЛОВМИСНИК НЕ МОЖЕ ЗАДОВОЛЬНИТИ.
//
//   Прийнятий рядок складається ВИКЛЮЧНО з перелічених дозволених символів
//   і має вигляд: коренева коса риска, а далі непорожні сегменти, відокремлені
//   рівно однією косою рискою.
//
// З цього випливає все, що в списку заборон довелося б перелічувати, — і
// кожна форма не проходить через ЄДИНУ причину, а не через окремий рядок:
//
//   · щоб рядок зробив чужий хост, треба або схему (`https:`, `javascript:`,
//     `data:` — двокрапка не дозволена), або два слеші підряд (`//host` —
//     порожнього сегмента не дозволено), або зворотну скісну (`\\host`,
//     `/\host` — браузер читає її як `/`; її немає серед дозволених символів);
//   · пробіл, табуляція й перенос рядка не дозволені теж: URL-парсер викидає
//     табуляцію та переноси МОВЧКИ, і з `/<TAB>/host` виходить `//host`;
//   · щоб приховати слеш чи двокрапку від перевірки, їх треба закодувати
//     (`%2f`, `%5c`, `%3a`, подвійно `%252f`) — а `%` не дозволений ЗОВСІМ.
//     Рядок, у якому немає `%`, лишається собою після будь-якої кількості
//     декодувань: «декодування» для нього — тотожність, тож хто б і скільки
//     разів його не розкодовував далі, нового слеша не з'явиться;
//   · `@` (`https://evil@host`, `/@host`) не дозволений: символу немає в
//     алфавіті, а не стоїть у списку «заборонене».
//
// Ціна, названа прямо: легітимна адреса, якій потрібне кодування, теж не
// пройде й піде на типове місце. Це не гіпотеза, так пише сам браузер:
// `URLSearchParams` кодує кому як `%2C`, пробіл як `+`, не-ASCII як `%XX`
// (`encodeURIComponent` пише пробіл як `%20`), тож правило сьогодні відхиляє
// справжні адреси НАШОГО сайту: `/map?types=camping%2Caire`,
// `/search?q=plage+du+sud`, `/search?q=W%C3%BCrzburg`. Приймається лише шлях
// із сегментів і, за потреби, простий запит із того самого алфавіту плюс `=`
// та `&` (`/map?types=camping`, `?a=1&b=2`).
//
// 🔴 Сьогодні цього досить лише тому, що місце повернення записує ЄДИНИЙ
// виклик: `rememberReturn` кличе тільки `AccountCabinet`, а він живе тільки на
// `/account`. Це властивість того виклику, а не правила: «усі адреси, з яких
// повертатимуть» правило НЕ покриває. Коли повернення зʼявиться з мапи й
// пошуку, їхні адреси МОВЧКИ падатимуть на `/`, і жоден тест цього не
// помітить. Що робити із запитами, яким потрібне відсоткове кодування, це
// окреме рішення, і його треба ухвалити тоді, разом із тим викликом, якому
// воно потрібне. `%` не дозволений навмисно (без нього «декодування» тотожне),
// а допуск `%` тягне подвійне декодування, рівно ту площину, де зʼявляються
// обходи, тож у це правило його не додають між іншим.
//
// 🔴 Перевірка лежить поруч із ПРОТИЛЕЖНОЮ: `return-path.spec.ts` ганяє тисячі
// рядків із ворожих шматків через `new URL(…, origin)` — парсер самого
// браузера, не наш — і вимагає: усе, що ми прийняли, лишається на нашому
// origin. Корпус там зібрано із зловмисних шматків, а не з форми перевірки.

/** Куди йти, коли немає, куди повернути, або те, що є, не годиться. */
export const DEFAULT_RETURN = '/';

/** Ключ у `sessionStorage`. Пише його лише `rememberReturn`. */
export const RETURN_KEY = 'camptribe.return';

/**
 * Скільки живе записане місце повернення.
 *
 * 15 хвилин — число макета («Намір живе 15 хвилин — і не довше»): людина,
 * яка вчора не дійшла до кінця, не має сьогодні входити в акаунт і
 * опинятись там, куди вже забула йти. Прострочене викидається мовчки.
 */
export const RETURN_TTL_MS = 15 * 60 * 1000;

/** Довше за це — не адреса сторінки, а спроба покласти щось у сховище. */
export const MAX_RETURN_LENGTH = 512;

// Дозволені символи сегмента: незарезервовані за RFC 3986 (літери, цифри,
// `-` `.` `_` `~`). Нічого, що URL-парсер чи проксі читає по-особливому.
const SEGMENT = '[A-Za-z0-9._~-]+';
// Запит: ті самі символи плюс `=` і `&`. Без `/`, `?`, `%`, `+`, `#`.
const QUERY = '[A-Za-z0-9._~=&-]*';

// `/` або `/seg(/seg)*` з необовʼязковою кінцевою `/`, далі необовʼязковий `?query`.
const RETURN_SHAPE = new RegExp(`^/(?:${SEGMENT}(?:/${SEGMENT})*/?)?(?:\\?${QUERY})?$`);

/**
 * Чи годиться це як місце повернення.
 *
 * Приймає лише рядок, лише в межах довжини й лише ту форму, що описана вгорі.
 */
export function isReturnPath(raw: unknown): raw is string {
  // 🔴 `typeof`, а не лише регулярка: `RegExp.test(['/account'])` перетворює
  // масив на рядок `/account` і каже «так», а ми повернули б МАСИВ.
  if (typeof raw !== 'string') return false;
  if (raw.length > MAX_RETURN_LENGTH) return false;
  return RETURN_SHAPE.test(raw);
}

/** Місце повернення або типове. Ніколи не кидає і ніколи не повертає чужого. */
export function safeReturnPath(raw: unknown): string {
  return isReturnPath(raw) ? raw : DEFAULT_RETURN;
}

// ── Сховище ───────────────────────────────────────────────────────────

type Store = Pick<Storage, 'getItem' | 'setItem' | 'removeItem'>;

/** `sessionStorage` або `null`: у приватному вікні й за блокування кидає. */
function tabStorage(): Store | null {
  try {
    return typeof window === 'undefined' ? null : window.sessionStorage;
  } catch {
    return null;
  }
}

/**
 * Запамʼятати, куди повернути людину після входу.
 *
 * Викликається ОДНИМ місцем — коли сторінка за логіном відправляє на /login —
 * і з адресою тієї ж сторінки. Те, що не годиться, не записується взагалі
 * (`false`): краще типове місце, ніж сумнівне.
 */
export function rememberReturn(
  path: unknown,
  storage: Store | null = tabStorage(),
  now: number = Date.now(),
): boolean {
  if (!isReturnPath(path)) return false;
  try {
    storage?.setItem(RETURN_KEY, JSON.stringify({ path, at: now }));
    return storage !== null;
  } catch {
    return false;
  }
}

/**
 * Забрати записане місце повернення — один раз — або типове.
 *
 * 🔴 ЗАПИС ВИДАЛЯЄТЬСЯ НА КОЖНОМУ ШЛЯХУ, ще до читання: добрий, сумнівний,
 * прострочений і зіпсований. Тому невдала навігація не зациклить людину на
 * одному й тому ж місці, а зіпсований запис не лежить, чекаючи наступного
 * входу.
 *
 * 🔴 ЗНАЧЕННЯ З СХОВИЩА НЕ ВІРИТЬСЯ. Те, що там лежить, мало записати
 * `rememberReturn`, але сховище — це не сейф: його можна залити з консолі,
 * з розширення, з XSS. Тож прочитане проходить ту саму `safeReturnPath`, що
 * й записане.
 *
 * Вік: `at` у майбутньому — теж не годиться (годинник, що збився, або
 * підроблений запис, який інакше жив би вічно).
 */
export function takeReturn(
  storage: Store | null = tabStorage(),
  now: number = Date.now(),
): string {
  if (storage === null) return DEFAULT_RETURN;
  let raw: string | null;
  try {
    raw = storage.getItem(RETURN_KEY);
    storage.removeItem(RETURN_KEY);
  } catch {
    return DEFAULT_RETURN;
  }
  if (raw === null) return DEFAULT_RETURN;

  let entry: unknown;
  try {
    entry = JSON.parse(raw);
  } catch {
    return DEFAULT_RETURN;
  }
  if (typeof entry !== 'object' || entry === null) return DEFAULT_RETURN;
  const { path, at } = entry as { path?: unknown; at?: unknown };
  if (typeof at !== 'number' || !Number.isFinite(at)) return DEFAULT_RETURN;
  const age = now - at;
  if (age < 0 || age >= RETURN_TTL_MS) return DEFAULT_RETURN;
  return safeReturnPath(path);
}
