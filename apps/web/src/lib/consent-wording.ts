// натисканням не має межі. Тому сторінка називає номер, який вона відрендерила,
// а сервер приймає його лише якщо він чинний (інакше 409 «перезавантажте»).
//
// 🔴 КЛІЄНТ НАДСИЛАЄ НОМЕР, НЕ ТЕКСТ. Текст бере сервер із реєстру
// (`apps/api/src/consent/wordings.ts`); вигадати версію, якої там немає, не
// вийде.
//
// 🔴 ЦЕ ЧИСЛО — ТРЕТЯ КОПІЯ ТОГО Ж ФАКТУ, і воно розійдеться мовчки, якщо ніхто
