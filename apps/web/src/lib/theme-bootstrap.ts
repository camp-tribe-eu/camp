/**
 * 🔴 ДРУГА КОПІЯ КЛЮЧА, І ВОНА ТУТ НАВМИСНО. Скрипт у `<head>` ставиться
 * з серверного макета й не може імпортувати з клієнтського компонента, а
 * сторож правових сторінок вимагає, щоб ключ був ЛІТЕРАЛОМ у тому файлі,
 * де стоїть `.setItem(` (`components/theme-toggle.tsx`). Розійтись цим
 * двом не дає `tests/unit/theme-key.spec.ts`.
 */
const THEME_KEY = 'camptribe.theme';

export type ThemeChoice = 'system' | 'light' | 'dark';

/**
 * 🔴 БЕЗ ЦЬОГО СКРИПТА БУВ БИ СПАЛАХ. React ставить атрибут після
 * гідратації, тобто читач із обраною темною темою встиг би побачити білу
 * сторінку. Тому вибір читається в `<head>`, синхронно.
 *
 * 🔴 Скрипт нічого не вирішує сам: він лише переносить ЗБЕРЕЖЕНИЙ вибір
 * на `<html>`. Немає вибору — немає атрибута, і сайт іде за системою,
 * як і описано в globals.css (`:root:not([data-theme="light"])`
 * усередині `@media (prefers-color-scheme: dark)`).
 *
 * `localStorage` кидає в приватному вікні й при заблокованих даних
 * сайту, тож читання загорнуте.
 */
export const THEME_BOOTSTRAP = `(function(){try{var t=localStorage.getItem('${THEME_KEY}');if(t==='dark'||t==='light'){document.documentElement.dataset.theme=t}}catch(e){}})();`;
