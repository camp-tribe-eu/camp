import { rememberReturn } from '@/lib/return-path';

/**
 * «Вхід — не сторінка, а пауза посеред дії». CAMP-227.
 *
 * 🔴 ЦЕ ОДНЕ МІСЦЕ, А НЕ ЧОТИРИ. Макет називає чотири точки, де виникає
 * стіна входу: зберегти маршрут, зберегти кемпінг, надіслати фото,
 * надіслати заявку власника. Кабінет робив це своїм рядком, сторінки
 * заявки й листингів не робили взагалі — і людина, яка не ввійшла,
 * впиралась у глухий кут замість того, щоб повернутись у дію.
 *
 * Чотири копії одного рішення — це чотири місця, де його можна забути
 * або зробити інакше. Тому воно тут, і приймає все, що йому треба,
 * аргументами: функція перевіряється без React і без браузера.
 *
 * 🔴 ЧОМУ НЕМАЄ Й НЕ БУДЕ `?next=`. Параметр у посиланні — це open
 * redirect: лист із `?next=` на чужий домен відправить людину туди вже
 * ПІСЛЯ успішного входу, коли вона нам довіряє. Адреса повернення
 * береться ЛИШЕ з того, де людина стоїть зараз, і проходить
 * `isReturnPath`, який не пропускає ані схеми, ані хоста.
 */
export type Where = { pathname: string; search: string };

export function pauseForLogin(
  where: Where,
  go: (to: string) => void,
  remember: (path: unknown) => boolean = rememberReturn,
): void {
  // 🔴 Записуємо ДО переходу. Інакше навігація може зняти сторінку
  // раніше, ніж намір ляже в сховище, і людина повернеться на типове
  // місце — мовчки, і лише іноді.
  remember(`${where.pathname}${where.search}`);
  go('/login');
}

/**
 * Чи означає ця відповідь API, що треба поставити паузу.
 *
 * 🔴 ОКРЕМА ФУНКЦІЯ, БО «НЕ ВВІЙШОВ» І «НІЧОГО НЕМАЄ» — РІЗНЕ.
 * `/account/listings` показувала «ви ще не підтвердили жодного листингу»
 * людині, яка просто не ввійшла. Це не порожній список, це невідомість,
 * і сказати замість неї твердження — значить збрехати.
 */
export const needsLogin = (kind: string): boolean => kind === 'signed-out';
