// CAMP-365 — розбір тексту, що приходить із CMS.
//
// 🔴 ЧОМУ ЦЕ ВЗАГАЛІ ПОТРІБНО, І ЧОМУ БЕЗ БІБЛІОТЕКИ.
//
// Дім уже рендерить тіло з бази: `guides/[slug]/page.tsx` ділить текст
// на блоки по порожньому рядку, рядок із «- » робить списком, решту —
// абзацом. Формат простий і свідомий: ні markdown-бібліотеки, ні
// `dangerouslySetInnerHTML` в репозиторії немає жодної, а CI гейтиться
// на вразливості залежностей — тож кожна нова бібліотека це постійна
// ціна.
//
// Але цей формат не виражає ДВОХ речей, без яких текст із CMS не
// замінить текст із коду:
//   • посилання ВСЕРЕДИНІ речення — `/about` має його на «Legal
//     notice», і 1 256 гайдів не можуть поставити жодного внутрішнього
//     посилання в тілі;
//   • виділення — в `/about` ним позначено речення, яке коментар поруч
//     називає найважливішим на сторінці.
//
// 🔴 ЧОМУ ЦЕ БЕЗПЕЧНО, хоч текст редагує людина, а не рецензія.
//
// Розбір НЕ будує HTML-рядків. Він повертає опис, з якого React робить
// елементи, а React екранує текст сам. Тобто вставити розмітку через
// поле CMS неможливо за побудовою — не тому, що ми щось вичищаємо, а
// тому, що зібраного HTML тут немає взагалі.
//
// Окремо перевіряються адреси посилань: `javascript:` в `href` це
// виконання коду, і воно пройшло б повз React. Тому дозволені схеми
// перелічені, а не заборонені — список заборон обходять новим словом.

/** Шматок рядка: або звичайний текст, або посилання, або виділення. */
export type Inline =
  | { kind: "text"; text: string }
  | { kind: "strong"; text: string }
  | { kind: "link"; text: string; href: string };

/** Блок: абзац, підзаголовок або список. */
export type Block =
  | { kind: "p"; spans: Inline[] }
  | { kind: "h2"; spans: Inline[] }
  | { kind: "ul"; items: Inline[][] };

/**
 * 🔴 ВЛАСТИВІСТЬ, А НЕ ПЕРЕЛІК НАПИСАНЬ.
 *
 * Перша редакція питала `href.startsWith("/") && !href.startsWith("//")`
 * і коментар поруч обіцяв, що «перевірка дивиться на другий символ
 * теж». Рецензія PR #301 це спростувала одним входом:
 *
 *     [Legal notice](/\evil.com)
 *
 * Браузер за WHATWG читає `\` як `/`, тож адреса веде на чужий сайт.
 * Заміряно мною: `new URL("/\evil.com", "https://camptribe.eu/guides/x")`
 * → `https://evil.com/`. Тест перелічував `//evil.example` і не
 * перелічував `/\` — бо то був СПИСОК, а список обходять новим
 * написанням.
 *
 * Тепер питається властивість: адресу РОЗБИРАЄ той самий механізм, що
 * й браузер, і внутрішньою вважається лише та, що після розбору
 * лишилась на нашому origin. Нових написань для цього не існує — вони
 * всі проходять через `new URL`.
 *
 * Зовнішні впізнаються за РОЗІБРАНОЮ схемою, а не за початком рядка:
 * `URL` нормалізує регістр, тож `HTTPS://` і `Mailto:` більше не
 * кидають (а кидок у серверному компоненті валить усю сторінку, не
 * одне посилання).
 */
const HREF_BASE = "https://camptribe.invalid/";
const HREF_BASE_ORIGIN = "https://camptribe.invalid";

/**
 * 🔴 ЦЕ ПРАВИЛО ЕКСПОРТУЄТЬСЯ, І ЦЕ НЕ ЗРУЧНІСТЬ, А ВИМОГА.
 *
 * Рецензія PR #303: я написав «те саме» правило ВДРУГЕ в `CtaButton`
 * (`href.startsWith("/")`) — і друга редакція не відхиляла НІЧОГО.
 * Заміряно на 10 входах: тут кидає 6, там рендерились усі 10, зокрема
 * `javascript:alert(1)` в `href` кнопки, яку редагує власник у CMS.
 *
 * Два незалежні формулювання одного правила розходяться завжди; тут
 * вони розійшлись одразу. Тому формулювання одне, і воно тут.
 */
export function isAllowedHref(href: string): boolean {
  // Шлях від кореня лишається внутрішнім, лише якщо після розбору він
  // НЕ поїхав на чужий origin. `//host` і `/\host` поїдуть.
  if (href.startsWith("/")) {
    try {
      return new URL(href, HREF_BASE).origin === HREF_BASE_ORIGIN;
    } catch {
      return false;
    }
  }

  // 🔴 ЗОВНІШНЄ МУСИТЬ НЕСТИ СХЕМУ САМЕ ТАК, ЯК НАПИСАНЕ.
  //
  // Розбір ВІДНОСНО бази вигадує схему тому, хто її не написав: голий
  // `\\evil.com` ставав `https://evil.com/` і проходив як звичайне
  // зовнішнє посилання. Знайдено власним тестом одразу після того, як
  // рецензія навчила питати властивість.
  //
  // Тому тут розбір БЕЗ бази: він кидає на всьому, що не має власної
  // схеми. Регістр нормалізує сам `URL`, тож `HTTPS://` і `Mailto:`
  // проходять, а `javascript:` відсікається за розібраним протоколом,
  // не за написанням.
  let u: URL;
  try {
    u = new URL(href);
  } catch {
    return false;
  }
  return u.protocol === "https:" || u.protocol === "mailto:";
}

/**
 * Підстановки виду `{{company.name}}`.
 *
 * 🔴 НЕВІДОМИЙ КЛЮЧ — ЦЕ ПОМИЛКА, А НЕ ПОРОЖНІЙ РЯДОК. Текст, де
 * підстановка мовчки зникла, читач побачить як «керується , Антверпен»
 * — тобто як поломку, якої ніхто не помітив на нашому боці. Порожнеча
 * неправильна завжди, а гучне падіння видно одразу.
 */
export function substitute(
  text: string,
  values: Readonly<Record<string, string>>,
): string {
  return text.replace(/\{\{([a-z0-9_.]+)\}\}/gi, (_, key: string) => {
    // 🔴 `values[key]` ДІСТАВАВ `Object.prototype`.
    //
    // Рецензія показала: `{{__proto__}}` давало «[object Object]»,
    // `{{constructor}}` — текст функції, так само `toString`,
    // `valueOf`, `hasOwnProperty`. Тобто замість обіцяного гучного
    // падіння читач бачив сміття, а ми — зелений тест. Питаємо ВЛАСНІ
    // ключі, а не те, що успадкувалось.
    const has = Object.prototype.hasOwnProperty.call(values, key);
    const v = has ? values[key] : undefined;
    if (!has || v === undefined) {
      throw new Error(
        `rich-text: невідома підстановка «{{${key}}}». Дозволені: ` +
          `${Object.keys(values).sort().join(", ") || "—"}. ` +
          "Текст із CMS не може вигадувати ключі.",
      );
    }
    return v;
  });
}

/**
 * Чи це ВНУТРІШНІЙ шлях — те саме питання, що й вище, але інша
 * відповідь: не «чи можна», а «чи наш». Потрібне рендерам, щоб обрати
 * між клієнтським переходом і звичайним якорем.
 */
export function isInternalHref(href: string): boolean {
  return href.startsWith("/") && isAllowedHref(href);
}

/**
 * Розбирає один рядок на текст, виділення й посилання.
 *
 * ⚠️ РОЗБІР КВАДРАТИЧНИЙ НА ПАТОЛОГІЧНОМУ ВХОДІ, і це названо, а не
 * замовчано. Заміряно рецензією PR #301 на `"[a](".repeat(n)`:
 * 20 тис. символів — 58 мс, 40 тис. — 228, 80 тис. — 909,
 * 160 тис. — 3641. Множник 4 на кожне подвоєння, тобто не експонента.
 *
 * Чому лишаємо як є: це поле редагує власник у CMS, а не анонім через
 * форму, і тіло сторінки такої довжини не буває. Якщо колись сюди
 * поїде текст із зовнішнього джерела, це перестане бути питанням
 * стійкості й стане питанням безпеки — тоді потрібна межа довжини
 * ПЕРЕД розбором, а не оптимізація виразу.
 */
export function parseInline(line: string): Inline[] {
  const out: Inline[] = [];
  // Один прохід, два візерунки: `[текст](адреса)` і `**текст**`.
  const re = /\[([^\]]+)\]\(([^)\s]+)\)|\*\*([^*]+)\*\*/g;
  let last = 0;
  let m: RegExpExecArray | null;

  while ((m = re.exec(line)) !== null) {
    if (m.index > last)
      out.push({ kind: "text", text: line.slice(last, m.index) });
    if (m[3] !== undefined) {
      out.push({ kind: "strong", text: m[3] });
    } else {
      const href = m[2];
      if (!isAllowedHref(href)) {
        throw new Error(
          `rich-text: адреса «${href}» не дозволена. Можна внутрішній ` +
            "шлях (/…), https:// або mailto:. Схеми перелічені, а не " +
            "заборонені — перелік заборон обходять новим словом.",
        );
      }
      out.push({ kind: "link", text: m[1], href });
    }
    last = re.lastIndex;
  }

  if (last < line.length) out.push({ kind: "text", text: line.slice(last) });
  return out;
}

/**
 * Текст → блоки. Формат той самий, що вже читає сторінка гайда:
 * порожній рядок ділить блоки, «- » робить список. Додано «## » для
 * підзаголовка.
 */
export function parseBlocks(text: string): Block[] {
  const blocks: Block[] = [];
  for (const raw of text.split(/\n\s*\n/)) {
    const block = raw.trim();
    if (!block) continue;

    if (block.startsWith("- ")) {
      blocks.push({
        kind: "ul",
        items: block
          .split("\n")
          .map((l) => l.replace(/^-\s*/, "").trim())
          .filter(Boolean)
          .map(parseInline),
      });
      continue;
    }

    if (block.startsWith("## ")) {
      blocks.push({ kind: "h2", spans: parseInline(block.slice(3).trim()) });
      continue;
    }

    // Переноси всередині абзацу — це один абзац, а не кілька: у полі
    // CMS вони зʼявляються від ширини вікна редактора, не від наміру.
    blocks.push({ kind: "p", spans: parseInline(block.replace(/\n/g, " ")) });
  }
  return blocks;
}
