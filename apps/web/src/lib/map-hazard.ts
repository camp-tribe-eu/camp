// CAMP-112: які саме кемпінги на мапі накриті чинним попередженням.
//
// 🔴 ПІДСВІЧУЄМО КЕМПІНГИ, А НЕ ПЛОЩІ, і це не художнє рішення.
// Геометрія зон — 26 318 EMMA_ID + 6 586 NUTS3 + 5 672 WARNCELLID
// полігонів, десятки мегабайтів; CAMP-287 заборонив віддавати її
// клієнтові, і попередження приїжджають БЕЗ неї. Малювати площі
// нічим. Але кожен кемпінг уже носить свої коди зон (крок 1 CAMP-287),
// тож зіставлення робиться там, де воно дешеве: у браузері, над
// списком, який і так завантажено.
//
// 🔴 ЗІСТАВЛЕННЯ ЗА ЗОНОЮ, НЕ ЗА КРАЇНОЮ, і я спершу вирішив навпаки.
//
// У базі 52 коди належать більш ніж одній країні: `EMMA_ID:NL014`
// накриває 645 кемпінгів у Німеччині й Нідерландах, `EMMA_ID:IT002` —
// 255 в Австрії й Італії; усього 3 656 кемпінгів носять такий код.
// Я написав тест, що голландське попередження не сміє чіпати
// німецький кемпінг. Тест упав, і розсудило третє джерело: резолвер
// робить `ST_Contains(z.geom, s.location)` і має власний самотест —
// «зона мусить МІСТИТИ точку, не лише бути поруч». Код на кемпінгу
// означає, що точка ГЕОМЕТРИЧНО всередині зони.
//
// Тобто німецький кемпінг усередині голландської зони справді стоїть
// у площі, про яку попередила KNMI. Погода не зупиняється на кордоні;
// клаузула 5.3 змушує назвати службу, і читач бачить «KNMI». Сховати
// це означало б сказати «спокійно» під штормом.
//
// Межа, яку перетинати НЕ можна, інша: збіг країни без збігу зони.
// Хорватське попередження на всіх хорватських кемпінгах — тривога
// там, де її немає, і картка забороняє це прямим текстом. Тому тут
// `applicableWarnings`, та сама, що на сторінці кемпінга: мапа й
// сторінка не сміють розходитись у відповіді про одне місце.

import {
  applicableWarnings,
  splitByForce,
  type Warning,
  type WarningFeed,
} from './warnings';

/** Коди зон, як чанк їх зшив: `EMMA_ID:HR008|NUTS3:HR033`. */
export const ZONES_KEY = 'z';

/** Розібрати те, що зшив `chunkBody`. Порожнє — порожній список. */
export const zonesOf = (joined: string | null | undefined): string[] =>
  typeof joined === 'string' && joined !== '' ? joined.split('|').filter(Boolean) : [];

/**
 * Рівень тривоги на кожен кемпінг, який її має.
 *
 * 🔴 ТІЛЬКИ ТІ, ХТО В СПИСКУ. Кемпінг без запису — не «спокійно», а
 * «нічого чинного не знайдено для нього». Різниця видна на мапі: шар
 * або показує стан усієї Європи, або не показує нічого, і друге чесніше
 * за підсвічені крапки без пояснення.
 *
 * 🔴 МАКСИМУМ, А НЕ ПЕРШИЙ. Кемпінг під жовтим вітром і помаранчевим
 * дощем — помаранчевий. Перший за списком залежав би від порядку у
 * фіді, тобто від чужого сортування.
 */
export function levelsBySlug(
  country: string,
  spots: readonly { slug: string; zones: string | null | undefined }[],
  feed: WarningFeed | null,
  now: Date,
): Map<string, number> {
  const out = new Map<string, number>();
  if (feed === null) return out;
  const warnings: readonly Warning[] = feed.warnings ?? [];
  if (warnings.length === 0) return out;

  for (const spot of spots) {
    // 🔴 ТУТ СТОЯЛО `if (codes.length === 0) continue;`, І ЙОГО
    // ПРИБРАНО ПІСЛЯ МУТАЦІЇ. Жоден випадок не міг його почервонити:
    // `applicableWarnings` із порожнім набором кодів і так не дає
    // збігів — порожні зони потрапляють у `unlocatable`, який мапа не
    // читає. Надлишковий захист, що дублює чужу умову, з часом
    // починає її підпирати: правиш одну, друга тримає, і жоден тест не
    // каже, що щось зламалось.
    const { applicable } = applicableWarnings(country, zonesOf(spot.zones), warnings);
    // 🔴 Вік ПОПЕРЕДЖЕННЯ, не лише вік знімка — той самий годинник, що
    // й на сторінці. Фетчер відсіює протерміновані на момент забору, а
    // знімок живе довше за це.
    const live = splitByForce(applicable, now).inForce;
    let max = 0;
    for (const w of live) {
      const lv = typeof w.level === 'number' ? w.level : 0;
      if (lv > max) max = lv;
    }
    if (max > 0) out.set(spot.slug, max);
  }
  return out;
}

/**
 * Скільки показувати рівнів — і чому всі.
 *
 * 🔴 ЗАМІРЯНО 13.10.2026, 183 чинні попередження по 27 фідах. Картка
 * побоювалась, що «жовтих багато, і шар, де завжди щось світиться,
 * перестають помічати». Замір цього не підтвердив:
 *
 *   жовтий і вище (>= 2)       2 805 кемпінгів із 52 907   5,3%
 *   помаранчевий і вище (>= 3) 1 040                       2,0%
 *   червоний (4)                  21                       0,04%
 *
 * Один із девʼятнадцяти — не «завжди щось світиться». А викинути
 * жовтий означало б вирішити за водія, що жовтий вітер для шестиметрового
 * фургона неважливий, тобто ОЦІНИТИ ризик — рівно те, що картка
 * забороняє. Рівні розрізняються кольором, а не мовчанням.
 *
 * 🔴 Це один зріз. У континентальний шторм частка буде іншою, тому шар
 * мусить лишатись читабельним і тоді: червоне має відрізнятись від
 * жовтого, а не тонути в ньому.
 */
export const SHOWN_LEVELS = [2, 3, 4] as const;

/** Рівень 1 — зелений, тобто ВІДСУТНІСТЬ попередження. Його тут бути не може. */
export const isShownLevel = (level: number): boolean =>
  (SHOWN_LEVELS as readonly number[]).includes(level);
