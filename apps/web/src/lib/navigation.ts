import { apiFetch } from "./api";

// CAMP-365 — меню шапки приходить із бази, а не з масиву в коді.
//
// 🔴 ЩО САМЕ ЦЕЙ ФАЙЛ ЗАБИРАЄ З КОДУ, І ЩО ВІН НАТОМІСТЬ ВИНЕН.
//
// Доти меню жило списком `NAV` у `site-chrome.tsx`. Той список мав
// властивість, якої ніхто не називав уголос: **мертве посилання в меню
// було неможливе**. Щоб його додати, треба було змінити файл, а файл
// читає рецензія і CI.
//
// База цієї властивості не має — власник може вписати пункт на
// сторінку, якої немає. Тому разом із переїздом стоїть сторож
// `tests/e2e/navigation.spec.ts`: він бере КОЖЕН пункт із бази й
// доводить, що той відкривається і що читач до нього дістанеться.

/** Пункт меню так, як його віддає API. */
export interface NavItem {
  href: string;
  label: string;
  /** Підпункти в порядку `sort`. Порожній масив, не null. */
  children: NavItem[];
}

/**
 * 🔴 МІТКА, А НЕ ХВИЛИНА — І ЧОМУ ПЕРША РЕДАКЦІЯ БУЛА НЕБЕЗПЕЧНОЮ.
 *
 * Спершу тут стояло `revalidate: 60`: «меню одне на весь сайт, тож це
 * один запит на хвилину». Число правильне, валюта — ні.
 *
 * Цей запит живе в КОРЕНЕВОМУ макеті, а Next бере МІНІМУМ витримки по
 * всьому дереву маршруту. Вихідники 15.5.27,
 * `server/lib/patch-fetch.js`: «if the value is less than the current
 * revalidate value, we should update the revalidate» —
 * `finalRevalidate < revalidateStore.revalidate → revalidateStore.
 * revalidate = finalRevalidate`.
 *
 * Отже 60 секунд у макеті опускали до 60 секунд УСІ сторінки сайту —
 * десятки тисяч, замість доби. Рецензія заміряла це на ізольованому
 * Next: сторінка з власним `revalidate: 86400` друкувалась як
 * «Revalidate 1m», а варто прибрати фетч із макета — знову «1d».
 *
 * Я порахував запити до API. Вузьким місцем були перемальовування
 * сторінок.
 *
 * ТОМУ ТУТ ДОБА ЯК СТЕЛЯ (те саме число, що й у решти викликів — не
 * вигадане тут) ПЛЮС МІТКА для миттєвого скидання. Мітка нічого не
 * опускає: її скидає `revalidateTag`, а не годинник.
 */
export const NAV_TAG = 'navigation';

/**
 * Як швидко правка меню в CMS доходить до читача.
 *
 * 🔴 ЦЕ ЧИСЛО ЗАМІНИЛО ГАЧОК, І ОСЬ ЧОМУ. Тут стояла доба з припискою
 * «гачок скине мітку, і правка зʼявиться за секунди». Заміряно на проді
 * 26.10.2026: один `revalidateTag('navigation')` переводив 55 269
 * сторінок кемпінгів і 1 256 гайдів у 404 ДО ПЕРЕЗАПУСКУ СЛУЖБИ
 * (CAMP-396). Гачок роззброєний, `ALLOWED_TAGS` порожній.
 *
 * 🔴 А ВИТРИМКА — БЕЗПЕЧНА, І ЦЕ ТЕЖ ЗАМІР, А НЕ ПРИПУЩЕННЯ. Дослід
 * 26.10.2026: процес із тією самою збіркою прожив 82 хвилини при
 * витримці 3600 с — вікно минуло із запасом, і жодна динамічна сторінка
 * не впала. Тобто ламає САМЕ виклик мітки, а не перевидання за часом.
 *
 * 🔴 ЦЕ ЧИСЛО ТЯГНЕ ЗА СОБОЮ ВЕСЬ САЙТ. Next бере МІНІМУМ витримки по
 * дереву маршруту (`server/lib/patch-fetch.js`), а меню живе в
 * кореневому макеті — тож ця цифра стає витримкою кожної сторінки.
 * Ціна одного перевидання заміряна: ~34 мс (41/38/38 мс проти 3,7 мс на
 * теплій сторінці). Чверть години — компроміс: правка меню доходить за
 * розумний час, і жодна сторінка не перевидається частіше.
 *
 * Чесне формулювання для картки: не «за секунди», а «у межах 15 хвилин».
 */
export const NAV_REVALIDATE_SECONDS = 900;

/**
 * Пункти шапки з бази.
 *
 * 🔴 ПОРОЖНЄ МЕНЮ — ЦЕ ПОМИЛКА, А НЕ ПОРОЖНІЙ МАСИВ.
 *
 * Сайт без навігації зламаний для читача сильніше, ніж сайт, що не
 * зібрався. Тихо віддати `[]` означало б прокласти шлях, яким поломка
 * доїде до людини: шапка без жодного посилання виглядає як дизайн, а не
 * як збій. Тому тут виняток.
 *
 * Що це дає на кожному з двох шляхів:
 *   • збірка — падає гучно, і ми не викладаємо сайт без меню;
 *   • перебудова на живому сервері — Next лишає попередню (справну)
 *     сторінку, бо нова не вдалась. Тобто читач бачить старе меню,
 *     а не порожнє.
 *
 * 🔴 ЗАПАСНОГО СПИСКУ В КОДІ ТУТ НЕМАЄ НАВМИСНО. Він повернув би той
 * самий хардкод, який картка прибирає, і зробив би збій невидимим:
 * меню малювалось би «правильно» й тоді, коли база недосяжна.
 */
export async function headerNav(): Promise<NavItem[]> {
  const res = await apiFetch("/navigation", {
    next: { revalidate: NAV_REVALIDATE_SECONDS, tags: [NAV_TAG] },
  });
  if (!res.ok) {
    throw new Error(
      `меню недосяжне: GET /navigation → ${res.status}. ` +
        "Шапка без пунктів — зламаний сайт, тож збірка зупиняється тут.",
    );
  }

  const body = (await res.json()) as Record<string, NavItem[] | undefined>;
  const items = body.header ?? [];
  if (items.length === 0) {
    throw new Error(
      "меню шапки порожнє: /navigation віддав 200, але жодного пункту " +
        "у `header`. Перевір таблицю `navigation` (visible = true) і " +
        "переклади: пункт без підпису навмисно не виходить із API.",
    );
  }
  return items;
}
