'use client';

import { useEffect, useState } from 'react';

/**
 * CAMP-188 — рік у копірайті, який справді міняється сам.
 *
 * 🔴 ЧОМУ НЕ ПРОСТО `new Date().getFullYear()` У РОЗМІТЦІ.
 *
 * Власник попросив, щоб рік змінювався «кожен новий рік сам, без
 * людини». У серверному компоненті цей виклик обчислюється **на момент
 * ЗБІРКИ**, а не показу. Заміряно 20.10.2026: сторінки статичні
 * (`legal/[slug]/page.tsx` має `dynamicParams = false`), а в
 * `.github/workflows/` немає жодного воркфлоу деплою — ні планового, ні
 * ручного. Тобто ніщо не перезбирає сайт саме по собі.
 *
 * Отже 1 січня 2027 року підвал і далі казав би «© 2026», доки хтось не
 * запустив би збірку руками. Рівно та людина, якої тут бути не мало.
 *
 * 🔴 ЧОМУ ПОЧАТКОВЕ ЗНАЧЕННЯ — РІК ЗБІРКИ, А НЕ ПОРОЖНЬО.
 *
 * Перша думка була рендерити порожньо до гідрації. Це гірше: читач без
 * JS (і будь-який сканер, що не виконує скриптів) побачив би «© .
 * UTD BV» — тобто поломку замість трохи застарілого року. Рік збірки
 * помилковий щонайбільше кілька місяців і лише до першого перезбирання;
 * порожнеча неправильна завжди.
 *
 * `suppressHydrationWarning` тут не глушить дефект, а визнає навмисну
 * розбіжність: саме ця розбіжність і є роботою компонента.
 */
export function CurrentYear() {
  const [year, setYear] = useState(() => new Date().getFullYear());

  useEffect(() => {
    // 🔴 МЕЖІ ЦЬОГО, ЗАМІРЯНІ, А НЕ ПРИПУЩЕНІ.
    //
    // Оновлюється на КОЖНОМУ повному завантаженні сторінки: і
    // ініціалізатор `useState`, і цей ефект виконуються в браузері
    // (перевірено — `getFullYear` приїздить у клієнтський `layout.js`).
    //
    // НЕ оновлюється при клієнтському переході між сторінками: підвал
    // живе в кореневому макеті, який Next між маршрутами НЕ
    // перемонтовує, тож ефект відпрацьовує один раз. Я спершу написав
    // тут протилежне й перевірив — підмінив годинник на 2031, перейшов
    // на сусідню сторінку, рік лишився 2026.
    //
    // Тобто вкладка, відкрита через північ 31 грудня, покаже старий рік
    // до першого перезавантаження. Це прийнятно: ніхто не читає
    // копірайт секунда в секунду, а людини для цього все одно не
    // потрібно.
    setYear(new Date().getFullYear());
  }, []);

  return <span suppressHydrationWarning>{year}</span>;
}
