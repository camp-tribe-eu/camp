'use client';

import { useEffect, useState } from 'react';

/**
 * CAMP-188 — рік у копірайті, який справді міняється сам.
 *
 * 🔴 ЧОМУ НЕ ПРОСТО `new Date().getFullYear()` У РОЗМІТЦІ.
 *
 * Власник попросив, щоб рік змінювався «кожен новий рік сам, без
 * людини». У серверному компоненті цей виклик обчислюється **на момент
 * ЗБІРКИ**, а не показу. Заміряно 20.10.2026: сторінки статичні
 * (`legal/[slug]/page.tsx` має `dynamicParams = false`), а в
 * `.github/workflows/` немає жодного воркфлоу деплою — ні планового, ні
 * ручного. Отже 1 січня 2027 підвал казав би «© 2026», доки хтось не
 * перезібрав би руками. Рівно та людина, якої бути не мало.
 *
 * 🔴 ЧОМУ ПОЧАТКОВЕ ЗНАЧЕННЯ ПРИХОДИТЬ ПРОПОМ, А НЕ РАХУЄТЬСЯ ТУТ.
 *
 * Перша редакція писала `useState(() => new Date().getFullYear())` — і
 * НЕ ПРАЦЮВАЛА. Знайшла рецензія PR #294, з посиланням на код тієї
 * збірки React, що поїде: у гілці гідрації тексту
 * `suppressHydrationWarning === true` приймає розбіжність і **не
 * позначає вузол на оновлення**, тобто серверний текст лишається в DOM.
 * А ініціалізатор `useState` на клієнті вже порахував рік БРАУЗЕРА, тож
 * `setYear(той самий рік)` — bail-out без перерендеру. Разом: у DOM
 * назавжди лишався рік збірки. Рівно той дефект, який цей компонент мав
 * прибрати.
 *
 * Тепер початкове значення — серверний рік, переданий пропом. Тоді:
 *   • SSR і перший клієнтський рендер збігаються ТОЧНО, тож
 *     `suppressHydrationWarning` більше не потрібен — і не глушить нічого;
 *   • ефект ставить рік браузера, і коли роки різні, це СПРАВЖНЯ зміна
 *     стану, тобто перерендер і оновлений DOM.
 *
 * Заміряно на живій сторінці: сервер віддав 2019, після гідрації в DOM
 * стало 2026 — тобто шлях «ефект → DOM» справді оновлює текст.
 *
 * 🔴 ЧОМУ ПРОП, А НЕ ПОРОЖНЕЧА. Читач без JS (і будь-який сканер, що не
 * виконує скриптів) побачив би «© . UTD BV» — поломку замість трохи
 * застарілого числа. Рік збірки помилковий щонайбільше кілька місяців;
 * порожнеча неправильна завжди.
 */
export function CurrentYear({ fallback }: { fallback: number }) {
  const [year, setYear] = useState(fallback);

  useEffect(() => {
    // 🔴 МЕЖІ ЦЬОГО, ЗАМІРЯНІ, А НЕ ПРИПУЩЕНІ.
    //
    // Оновлюється на КОЖНОМУ повному завантаженні сторінки.
    //
    // НЕ оновлюється при клієнтському переході між сторінками: підвал
    // живе в кореневому макеті, який Next між маршрутами НЕ
    // перемонтовує, тож ефект відпрацьовує один раз. Я спершу написав
    // тут протилежне й перевірив — підмінив годинник на 2031, перейшов
    // на сусідню сторінку, рік лишився 2026.
    //
    // Тобто вкладка, відкрита через північ 31 грудня, покаже старий рік
    // до першого перезавантаження. Це прийнятно: ніхто не читає
    // копірайт секунда в секунду, а людини для цього не потрібно.
    setYear(new Date().getFullYear());
  }, []);

  return <>{year}</>;
}
