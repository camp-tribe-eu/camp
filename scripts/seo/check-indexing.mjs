#!/usr/bin/env node
// CAMP-90: does this build actually say what we think it says?
//
//   node scripts/seo/check-indexing.mjs --expect closed
//   node scripts/seo/check-indexing.mjs --expect public
//
// The card asks for "a verification checklist before the first public
// launch". A checklist in a document is read once and then not; this is
// the same checklist, executable, and it fails the build.
//
// 🔴 It takes the expected mode as an argument rather than reading the
// environment, and that is the entire point. A checker that asks the
// build what mode it is in and then agrees with it cannot catch
// anything. Someone has to state the intent — CI states `closed`, and
// the day we launch, the release step states `public` and this is what
// proves every one of the four mechanisms flipped together.
//
// The four, all of which have to agree:
//
//   1. robots.txt        — full Disallow, and no sitemap: line, when closed
//   2. public/_headers   — X-Robots-Tag on every path, when closed
//   3. every built page  — meta robots noindex, when closed
//   4. the sitemap       — pages listed are indexable, when public
//
// Any one of them alone is a half-measure. A robots.txt Disallow with no
// header stops the crawl but lets a linked URL appear as a bare result;
// a meta tag with no header does nothing for the sitemap XML, llms.txt
// or the fonts.

import { readFileSync, existsSync } from 'node:fs';
import { glob } from 'node:fs/promises';
import path from 'node:path';

const args = process.argv.slice(2);
const expectIndex = args.indexOf('--expect');
const EXPECT = expectIndex >= 0 ? args[expectIndex + 1] : null;
const dirIndex = args.indexOf('--dir');
const ROOT =
  dirIndex >= 0 && args[dirIndex + 1]
    ? args[dirIndex + 1]
    : 'apps/web/.next/server/app';
// indexOf returns -1 when the flag is absent, and args[-1 + 1] is
// args[0] — which silently made the first argument the file path.
const headersIndex = args.indexOf('--headers');
const HEADERS_FILE =
  headersIndex >= 0 && args[headersIndex + 1]
    ? args[headersIndex + 1]
    : 'apps/web/public/_headers';

if (EXPECT !== 'closed' && EXPECT !== 'public') {
  console.error(
    'Usage: check-indexing.mjs --expect closed|public\n\n' +
      'The mode is stated, never inferred: a checker that reads the build\n' +
      'and then agrees with it proves nothing.',
  );
  process.exit(2);
}

const shouldBeIndexable = EXPECT === 'public';
const errors = [];
const read = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);
const NOINDEX = /noindex/i;

// ── 1. robots.txt ────────────────────────────────────────────────────────
const robots =
  read(path.join(ROOT, 'robots.txt.body')) ?? read(path.join(ROOT, 'robots.txt'));
if (!robots) {
  errors.push('robots.txt was not built');
} else {
  const blocksEverything = /^\s*Disallow:\s*\/\s*$/m.test(robots);
  const hasSitemap = /^\s*Sitemap:/mi.test(robots);

  if (shouldBeIndexable) {
    if (blocksEverything) {
      errors.push('robots.txt still blocks the whole site (Disallow: /)');
    }
    if (!hasSitemap) errors.push('robots.txt does not point at the sitemap');
  } else {
    if (!blocksEverything) {
      errors.push('robots.txt does not block the whole site');
    }
    if (hasSitemap) {
      errors.push(
        'robots.txt advertises a sitemap while blocking the crawl — ' +
          'contradictory instructions',
      );
    }
  }
}

// ── 2. the header file Cloudflare Pages actually reads ───────────────────
const headers = read(HEADERS_FILE);
if (!headers) {
  errors.push(
    `${HEADERS_FILE} is missing — run the build, it is generated by prebuild`,
  );
} else {
  const hasTag = /X-Robots-Tag:\s*noindex/i.test(headers);
  if (shouldBeIndexable && hasTag) {
    errors.push(
      '_headers still carries X-Robots-Tag: noindex — this is the classic ' +
        'way a site disappears from the index on launch day',
    );
  }
  if (!shouldBeIndexable && !hasTag) {
    errors.push('_headers has no X-Robots-Tag: noindex');
  }
}

// ── 3. every built page ──────────────────────────────────────────────────
const pages = [];
for await (const f of glob(`${ROOT}/**/*.html`)) pages.push(f);

let noindexPages = 0;
const wrong = [];
for (const file of pages) {
  const html = readFileSync(file, 'utf8');
  const meta = /<meta name="robots"[^>]*content="([^"]*)"/i.exec(html);
  const isNoindex = meta ? NOINDEX.test(meta[1]) : false;
  if (isNoindex) noindexPages++;

  const label = path.relative(ROOT, file).replace(/\.html$/, '');
  if (!shouldBeIndexable && !isNoindex) wrong.push(label);
}

if (!shouldBeIndexable && wrong.length) {
  errors.push(
    `${wrong.length} page(s) carry no noindex: ${wrong.slice(0, 5).join(', ')}` +
      (wrong.length > 5 ? ' …' : ''),
  );
}
if (shouldBeIndexable && noindexPages === pages.length) {
  errors.push('every page is noindex in a build that is meant to be public');
}
// 🔴 The other half, and the one a public build can silently lose: the
// thin-hub threshold from CAMP-71 and the four-import rule from CAMP-87
// both work by marking SOME pages noindex. Zero of them in a public
// build does not mean everything is fine — it means those rules stopped
// applying, and the only symptom would be thin pages entering the index.
if (shouldBeIndexable && noindexPages === 0) {
  errors.push(
    'no page is noindex in a public build — the thin-hub threshold ' +
      '(CAMP-71) and the missing-campsite rule (CAMP-87) have stopped ' +
      'applying',
  );
}

// ── 4. the sitemap, which must not contradict the rest ───────────────────
const sitemap =
  read(path.join(ROOT, 'sitemap.xml.body')) ??
  read(path.join(ROOT, 'sitemap.xml'));
if (!sitemap) {
  errors.push('sitemap.xml was not built');
}

console.log(`expected mode   ${EXPECT}`);
console.log(`pages           ${pages.length}`);
console.log(`noindex pages   ${noindexPages}`);
console.log(
  `robots.txt      ${
    robots ? (/Disallow:\s*\/\s*$/m.test(robots) ? 'blocks everything' : 'open') : 'MISSING'
  }`,
);
console.log(
  `X-Robots-Tag    ${
    headers ? (/X-Robots-Tag/i.test(headers) ? 'noindex, nofollow' : 'none') : 'MISSING'
  }`,
);

if (errors.length) {
  console.error(`\n✗ build does not match "${EXPECT}":`);
  for (const e of errors) console.error(`   ${e}`);
  console.error(
    '\nAll four mechanisms have to agree. A site that is half-closed is ' +
      'the worst of both:\nblocked from crawling, still listed as a bare URL.',
  );
  process.exit(1);
}

console.log(`\n✓ robots.txt, headers, pages and sitemap all agree on "${EXPECT}"`);
