#!/usr/bin/env bash
# Перевірка, яку треба ПРОГНАТИ, а не згадати.
#
# 🔴 ЧОМУ ЦЕ ІСНУЄ, ЧИСЛАМИ.
#
# Замір за 21.10.2026: 22 поломки, які я завіз сам і сам же виправляв
# наступним комітом. З них 18 були порушенням правила, яке ВЖЕ лежало в
# теці памʼяті — знання було, застосування ні. Того ж дня я дописав ще
# 8 правил і повторив ті самі класи.
#
# Класи, що повторились за одну добу:
#   одне правило у двох списках ......... 6
#   сторож, що не може почервоніти ...... 5
#   новий побратим поза інвентарем ...... 4
#   includes замість рівності множини ... 3
#   неповний прогін ..................... 3
#
# Цей файл б'є по «неповному прогону» й по частині «двох списків»: він
# ганяє ОБИДВА робочі простори і ті сторожі CI, що не потребують
# збірки. Те, що ловиться тут, коштувало 21.10 повного циклу CI
# (медіана 41 хв) щоразу.
#
# 🔴 ЧОГО ВІН НЕ МОЖЕ. Він не доведе, що новий сторож уміє червоніти —
# це робить мутація, і її треба прогнати руками. Тому в кінці стоять
# питання, відповідь на які має лежати в описі PR.
set -uo pipefail
cd "$(dirname "$0")/../.."
fail=0

# 🔴 БЕЗ ЦЬОГО НАБІР API ЧЕРВОНИЙ ЗАВЖДИ, А ЗАВЖДИ ЧЕРВОНА ПЕРЕВІРКА
# ГІРША ЗА ВІДСУТНЮ: її перестають читати.
#
# Чотирнадцять наборів у apps/api працюють із базою і СВІДОМО падають
# замість пропуску — їхній власний коментар каже чому: «пропущений
# тест читається так само, як пройдений». У CI змінну дає workflow;
# локально її треба задати, інакше 553 падіння щоразу.
export CAMP_TEST_DATABASE_URL="${CAMP_TEST_DATABASE_URL:-postgres://localhost:5432/camptribe_dev}"
printf 'база для тестів api: %s\n' "${CAMP_TEST_DATABASE_URL##*/}"

# 🔴 Назву кроку зберігаємо ДО `shift`: інакше у звіті про падіння
# стоїть імʼя команди замість кроку. Скрипт упіймав це на самому собі
# з першого ж прогону.
step() {
  label="$1"
  shift
  printf '\n— %s\n' "$label"
  if "$@" >/tmp/prepush.$$ 2>&1; then
    printf '  OK\n'
  else
    printf '  ПАДІННЯ: %s\n' "$label"
    tail -12 /tmp/prepush.$$ | sed 's/^/    /'
    fail=1
  fi
  rm -f /tmp/prepush.$$
}

# `npx --prefix` міняє пошук пакета, але НЕ робочу теку, тож шляхи
# треба задавати з неї. Теж знайдено першим прогоном цього скрипта.
step "юніти web (увесь проєкт, не лише свої файли)" \
  bash -c 'cd apps/web && npx playwright test --project=unit --reporter=line'

step "тести api" \
  bash -c 'cd apps/api && npm run test --silent'

# 🔴 ДВА ЛІНТИ, А НЕ ОДИН. У apps/api prettier обовʼязковий через
# eslint, у apps/web його немає зовсім. 21.10 я прогнав лише web і
# дістав червоний CI на відступах у міграції.
step "лінт web" bash -c 'cd apps/web && npx eslint src'
step "лінт api (prettier усередині)" \
  bash -c 'cd apps/api && npx eslint "src/**/*.ts" --max-warnings=0'

# Сторожі CI без збірки. Саме вони 21.10 упіймали непрочитаний тип
# файлу `.md` — двічі, бо я полагодив один із двох.
for g in check-hardcoded-counts check-country-count; do
  step "сторож $g" node "scripts/ci/$g.mjs"
  step "сторож $g — самоперевірка" node "scripts/ci/$g.mjs" --self-test
done

printf '\n'
if [ "$fail" -ne 0 ]; then
  printf 'НЕ пушити: щось упало вище.\n'
  exit 1
fi

cat <<'ASK'
Механічна частина чиста. Лишилось те, чого скрипт перевірити не може:

  1. Чи прогнав я МУТАЦІЮ проти кожного нового сторожа — і чи він
     почервонів? (21.10: мутацію мали 12 комітів із 34, і рівно там,
     де її не було, сиділи 5 сторожів, що не червоніють.)
  2. Чи лежить це правило ще десь другим списком? (6 випадків за добу.)
  3. Чи бачить сторож те, що перевіряє, у СЕРЕДОВИЩІ CI — секрети,
     браузер, база? (e2e на мітки впав у 4 браузерах саме тому.)
  4. Чи я на тій гілці? (3 рази за добу — ні.)

Відповідь на 1 має бути в описі PR числом: що зламав, що почервоніло.
ASK
