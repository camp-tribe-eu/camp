#!/usr/bin/env bash
# 🔴 МАЖОР POSTGRES У CI МУСИТЬ ДОРІВНЮВАТИ МАЖОРУ НА ПРОДІ.
#
# CI місяцями ганявся на образі postgis:16-3.4, тоді як прод — на 17.11.
# Тобто УСІ перевірки проходили не на тій мажорній версії, яку ми
# запускаємо. Ніхто цього не бачив, доки зовнішня подія (перехід
# `ubuntu-latest` на 26.04) не зробила розбіжність гучною: клієнт поїхав
# уперед, і дампи перестали відновлюватись. Образи вирівняли в #471, але
# РАЗОВО — ніщо не тримає їх разом надалі.
#
# 🔴 ЧОГО ЦЕЙ СТОРОЖ НЕ РОБИТЬ, І ЦЕ ГОЛОВНЕ. Він не чіпає клієнта.
# Попередня спроба (PR #473, закритий) читала мажор із сервера й
# ПІДМІНЯЛА клієнт під нього — і ламала `move-table.selftest.sh`, тоді як
# на main із тим самим раннером він зелений. Сторож, який щось
# встановлює, може зламати робочу збірку. Цей лише порівнює два числа.
#
# Обидва кінці дивляться на ОДНЕ джерело — `infra/pg-major`, — а не один
# на одного: інакше два переліки розходяться тихо, як і розійшлись.
#
# ЦІНА ХИБНОГО СПРАЦЮВАННЯ: збірка або виливання червоніє з двома
# числами в повідомленні. Виправлення очевидне: або підняти образ, або
# оновити записане число разом із продом.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
file="${CAMPTRIBE_PG_MAJOR_FILE:-${root}/infra/pg-major}"
[ -r "$file" ] || { echo "🔴 не читається ${file}" >&2; exit 2; }

want="$(tr -d '[:space:]' < "$file")"
case "$want" in
  ''|*[!0-9]*) echo "🔴 у ${file} не число: «${want}»" >&2; exit 2 ;;
esac

conn="${1:-${DATABASE_URL:-${CAMPTRIBE_SELFTEST_PG_BASE:-}}}"
[ -n "$conn" ] || { echo "🔴 нема рядка під'єднання" >&2; exit 2; }

num="${CAMPTRIBE_FAKE_SERVER_MAJOR_NUM:-$(psql "$conn" -tAqc 'SHOW server_version_num')}"
# 🔴 Не просто «непорожнє»: перша редакція приймала пробіл, арифметика
# давала 0, і СЕРВЕРНИЙ ЗБІЙ друкувався як «сервер 0» — тобто прикидався
# розбіжністю версій. Збій мусить виглядати збоєм.
num="$(printf '%s' "${num}" | tr -d '[:space:]')"
case "$num" in
  ''|*[!0-9]*) echo "🔴 SHOW server_version_num дав не число: «${num}» — це збій, а не версія" >&2; exit 2 ;;
esac
got=$(( num / 10000 ))

if [ "$got" != "$want" ]; then
  echo "🔴 мажор Postgres розійшовся: очікувано ${want} (${file}), сервер ${got}." >&2
  echo "   Або підніміть образ/прод до ${want}, або оновіть число РАЗОМ із продом." >&2
  echo "   Образи CI: .github/workflows/*.yml, рядки «image: postgis/postgis:»." >&2
  exit 1
fi
echo "pg major ${got} збігається з ${file}"
